/**
 * Returns the public image path for any tarot card object or identifier.
 */
export function getTarotCardImage(card) {
  if (!card) return '/tarot/major_00.jpg';
  
  if (typeof card === 'string') {
    return CARD_IMAGE_MAP[card] || `/tarot/${card}.jpg`;
  }
  
  if (card.image_url) return card.image_url;
  if (card.card_id && CARD_IMAGE_MAP[card.card_id]) return CARD_IMAGE_MAP[card.card_id];
  if (card.id && CARD_IMAGE_MAP[card.id]) return CARD_IMAGE_MAP[card.id];
  if (card.image_key && CARD_IMAGE_MAP[card.image_key]) return CARD_IMAGE_MAP[card.image_key];
  if (card.card_name && CARD_IMAGE_MAP[card.card_name]) return CARD_IMAGE_MAP[card.card_name];
  if (card.name && CARD_IMAGE_MAP[card.name]) return CARD_IMAGE_MAP[card.name];
  
  if (card.card_id) return `/tarot/${card.card_id}.jpg`;
  if (card.id) return `/tarot/${card.id}.jpg`;
  
  return '/tarot/major_00.jpg';
}
